-- ---------------------------------------------------------------------
-- 1. Table: comconstant
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.comconstant
(
    constant_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    constant_name VARCHAR(200) NOT NULL,
    category_name VARCHAR(100) NOT NULL,
    constant_value INTEGER NULL,
    isactive BOOLEAN NOT NULL DEFAULT TRUE,
    createdby VARCHAR(200) NULL,
    createddate TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    modifiedby VARCHAR(200) NULL,
    modifieddate TIMESTAMPTZ NULL
);

-- Indexes for fast lookup
CREATE INDEX IF NOT EXISTS idx_comconstant_category ON public.comconstant (category_name);
CREATE INDEX IF NOT EXISTS idx_comconstant_active ON public.comconstant (isactive);

